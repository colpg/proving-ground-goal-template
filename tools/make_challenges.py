#!/usr/bin/env python3
"""make_challenges.py [--check] [--closing CUT_ID] [--jobs FILE]

Writes a goal's challenge files from its manifests, using names only.

A goal keeps one manifest per problem in proving-ground/problems/ and one per cut in
proving-ground/cuts/. Every problem's statement is a named definition in the goal's library, so a
challenge never needs the statement's text:

    Problems/<id>.lean        theorem <theorem> : <statement> := sorry
    Problems/<id>_neg.lean    theorem <theorem>_neg : ¬ <statement> := sorry        (kind "settle" only)
    Problems/cut_<cut>.lean   theorem <cut theorem> (h1 : <child 1 statement>) ... : <parent statement> := sorry

With no option it writes those files. --check writes nothing and fails if any file on disk differs
from what would be written. --closing CUT_ID writes Proofs/<parent id>.lean, the short proof that
applies a completed cut to its children. --jobs FILE writes, as JSON, one judging job for every
answer file present (Proofs/<id>.lean, Proofs/<id>_neg.lean, Cuts/<cut>.lean).

Reads the manifests; writes only under Problems/ and Proofs/ and the --jobs file. Needs Python 3.11."""
import argparse, json, os, re, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_']*(\.[A-Za-z_][A-Za-z0-9_']*)*")
ID = re.compile(r"[a-z][a-z0-9_]{0,62}")
KINDS = ("prove", "settle", "construct", "certify")
HEAD = "-- Generated by tools/make_challenges.py from %s. Do not edit.\n"


def load(sub):
    out = {}
    d = os.path.join(ROOT, "proving-ground", sub)
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if f.endswith(".toml"):
            m = tomllib.load(open(os.path.join(d, f), "rb"))
            assert m.get("id") == f[:-5], "%s/%s: the id must equal the file name" % (sub, f)
            out[m["id"]] = m
    return out


def name(x, what):
    assert isinstance(x, str) and NAME.fullmatch(x), "%s is not a Lean name: %r" % (what, x)
    return x


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0], allow_abbrev=False)
    ap.add_argument("--check", action="store_true"); ap.add_argument("--closing"); ap.add_argument("--jobs")
    a = ap.parse_args()
    goal = tomllib.load(open(os.path.join(ROOT, "proving-ground", "goal.toml"), "rb"))
    stm = name(goal["statements"], "goal.statements"); axioms = goal["permitted_axioms"]
    probs, cuts = load("problems"), load("cuts")
    files = {}
    for pid, p in probs.items():
        assert ID.fullmatch(pid) and not pid.endswith("_neg") and not pid.startswith("cut_"), "problem id %r" % pid
        assert p["kind"] in KINDS, "%s: kind %r" % (pid, p["kind"])
        th, st = name(p["theorem"], pid + ".theorem"), name(p["statement"], pid + ".statement")
        for u in p.get("uses", []): assert u in probs, "%s uses an unknown problem %r" % (pid, u)
        src = HEAD % ("proving-ground/problems/%s.toml" % pid)
        files["Problems/%s.lean" % pid] = "import %s\n%s\ntheorem %s : %s := sorry\n" % (stm, src, th, st)
        if p["kind"] == "settle":
            files["Problems/%s_neg.lean" % pid] = "import %s\n%s\ntheorem %s_neg : ¬ %s := sorry\n" % (stm, src, th, st)
    for r in goal["roots"]: assert r in probs, "root %r is not a problem" % r
    for cid, c in cuts.items():
        assert ID.fullmatch(cid) and c["parent"] in probs and c["children"], "cut %r" % cid
        hyps = " ".join("(h%d : %s)" % (i + 1, probs[k]["statement"]) for i, k in enumerate(c["children"]))
        files["Problems/cut_%s.lean" % cid] = "import %s\n%s\ntheorem %s %s : %s := sorry\n" % (
            stm, HEAD % ("proving-ground/cuts/%s.toml" % cid), name(c["theorem"], cid + ".theorem"), hyps, probs[c["parent"]]["statement"])

    if a.closing:
        c = cuts[a.closing]; parent = probs[c["parent"]]
        imports = ["import Cuts.%s" % a.closing] + ["import Proofs.%s" % k for k in c["children"]]
        body = "%s\n-- The closing proof of cut %s: written from names, and judged like any other answer.\n\ntheorem %s : %s := %s %s\n" % (
            "\n".join(imports), a.closing, parent["theorem"], parent["statement"], c["theorem"], " ".join(probs[k]["theorem"] for k in c["children"]))
        open(os.path.join(ROOT, "Proofs", "%s.lean" % c["parent"]), "w", encoding="utf-8").write(body)
        print("wrote Proofs/%s.lean" % c["parent"]); return

    if a.jobs:
        jobs = []
        def job(label, ch, so, th):
            if os.path.exists(os.path.join(ROOT, so.replace(".", "/") + ".lean")):
                jobs.append({"label": label, "challenge_module": ch, "solution_module": so, "theorem_names": [th], "permitted_axioms": axioms})
        for pid, p in probs.items():
            job("proof of " + pid, "Problems." + pid, "Proofs." + pid, p["theorem"])
            if p["kind"] == "settle": job("refutation of " + pid, "Problems.%s_neg" % pid, "Proofs.%s_neg" % pid, p["theorem"] + "_neg")
        for cid, c in cuts.items(): job("implication of cut " + cid, "Problems.cut_" + cid, "Cuts." + cid, c["theorem"])
        json.dump(jobs, open(a.jobs, "w", encoding="utf-8"), indent=1); print("wrote %d jobs to %s" % (len(jobs), a.jobs)); return

    bad = []
    for rel, text in sorted(files.items()):
        path = os.path.join(ROOT, rel)
        if a.check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text: bad.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True); open(path, "w", encoding="utf-8").write(text)
    stray = [f for f in (os.listdir(os.path.join(ROOT, "Problems")) if os.path.isdir(os.path.join(ROOT, "Problems")) else []) if "Problems/" + f not in files]
    if a.check:
        if bad or stray: sys.exit("challenge files differ from the manifests: %s; not in any manifest: %s" % (bad, stray))
        print("%d challenge files match the manifests" % len(files))
    else:
        print("wrote %d challenge files%s" % (len(files), ("; not in any manifest: %s" % stray) if stray else ""))


if __name__ == "__main__":
    main()
